      "editorSuggestWidget.border": "#33334A",
      "editorSuggestWidget.foreground": "#D1D1D8",
      "editorSuggestWidget.selectedBackground": "#3A3A4A",
      "editorSuggestWidget.highlightForeground": "#D4AF37",
